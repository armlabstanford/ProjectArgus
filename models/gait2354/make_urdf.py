#!/usr/bin/env python3
"""Write src/argus_server/urdf/human_gait.urdf: the RViz human with gait2354 joints.

    ./models/gait2354/make_urdf.py

Starts from human.urdf (the Xsens-style body used for the arm model) and
  - turns the root into pelvis_tilt / pelvis_list / pelvis_rotation (gait2354's
    ground_pelvis order: about OpenSim z, then x, then y);
  - makes the leg joints revolute and names them after the gait2354
    coordinates (hip flexion / adduction / rotation, knee, ankle, subtalar, mtp)
    with the model's axes and ranges;
  - drives the trunk with lumbar_extension / bending / rotation;
  - fixes the arm joints (gait2354 has no arms).
OpenSim axes are Y up, Z right; the URDF uses ROS axes (X forward, Y left, Z up),
so an OpenSim axis (a, b, c) is (a, -c, b) here. Every URDF link frame is
aligned with the world at zero, like the gait2354 body frames.
"""

import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SOURCE = ROOT / "src" / "argus_server" / "urdf" / "human.urdf"
DEST = ROOT / "src" / "argus_server" / "urdf" / "human_gait.urdf"
MODEL = HERE / "model.osim"

# URDF joint -> gait2354 coordinate it becomes.
RENAME = {
    "r_x": "pelvis_tilt", "r_y": "pelvis_list", "r_z": "pelvis_rotation",
    "jRightHip_rotx": "hip_flexion_r", "jRightHip_roty": "hip_adduction_r", "jRightHip_rotz": "hip_rotation_r",
    "jLeftHip_rotx": "hip_flexion_l", "jLeftHip_roty": "hip_adduction_l", "jLeftHip_rotz": "hip_rotation_l",
    "jRightKnee_roty": "knee_angle_r", "jLeftKnee_roty": "knee_angle_l",
    # The chain order is rotx, roty, rotz; OpenSim turns the ankle before the subtalar joint.
    "jRightAnkle_rotx": "ankle_angle_r", "jRightAnkle_roty": "subtalar_angle_r", "jRightBallFoot_roty": "mtp_angle_r",
    "jLeftAnkle_rotx": "ankle_angle_l", "jLeftAnkle_roty": "subtalar_angle_l", "jLeftBallFoot_roty": "mtp_angle_l",
    "jL5S1_rotx": "lumbar_extension", "jL5S1_roty": "lumbar_bending", "jT9T8_rotz": "lumbar_rotation",
}


def model_axes_and_ranges():
    """{coordinate: (axis in the parent body frame, (lower, upper))} from the gait2354 CustomJoints."""
    root = ET.parse(MODEL).getroot()
    ranges = {c.get("name"): tuple(float(v) for v in c.findtext("range").split()) for c in root.iter("Coordinate")}
    axes = {}
    for joint in root.iter("CustomJoint"):
        for ta in joint.find("SpatialTransform").findall("TransformAxis"):
            coord = (ta.findtext("coordinates") or "").strip()
            if ta.get("name").startswith("rotation") and coord:
                axes[coord] = [float(v) for v in ta.findtext("axis").split()]
    return {c: (axes[c], ranges[c]) for c in axes}


def ros_axis(osim):
    a, b, c = osim
    return f"{a:g} {-c:g} {b:g}"


def main():
    tree = ET.parse(SOURCE)
    robot = tree.getroot()
    robot.set("name", "human_gait")
    coords = model_axes_and_ranges()
    renamed = set()
    for joint in robot.findall("joint"):
        name = joint.get("name")
        if name in RENAME:
            coord = RENAME[name]
            axis, (lower, upper) = coords[coord]
            joint.set("name", coord)
            joint.set("type", "revolute")
            for tag in ("axis", "limit", "mimic"):
                for el in joint.findall(tag):
                    joint.remove(el)
            ET.SubElement(joint, "axis", {"xyz": ros_axis(axis)})
            ET.SubElement(joint, "limit", {"lower": f"{lower:g}", "upper": f"{upper:g}", "effort": "100", "velocity": "10"})
            renamed.add(name)
        elif joint.get("type") in ("revolute", "continuous", "prismatic"):
            # The arm model's joints (and the root translations): fixed here.
            joint.set("type", "fixed")
            for tag in ("limit", "mimic"):
                for el in joint.findall(tag):
                    joint.remove(el)
    missing = set(RENAME) - renamed
    if missing:
        raise SystemExit(f"joints not found in {SOURCE.name}: {sorted(missing)}")
    ET.indent(tree, space="  ")
    DEST.write_text(
        "<?xml version=\"1.0\"?>\n"
        "<!-- Generated by models/gait2354/make_urdf.py from human.urdf; edit that script, not this file. -->\n"
        + ET.tostring(robot, encoding="unicode") + "\n")
    print(f"wrote {DEST} ({len(renamed)} gait2354 joints)")


if __name__ == "__main__":
    main()
