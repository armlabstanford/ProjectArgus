#!/usr/bin/env python3
"""Write src/argus_server/urdf/human_rajagopal_lower.urdf.

    ./models/rajagopal_lower/make_urdf.py

Same world-aligned Xsens skeleton as human_gait.urdf, but joint limits and the
knee axis follow Rajagopal 2015 instead of gait2354.

The URDF link frames are aligned with the world at zero (like gait2354), so
hip / pelvis / lumbar / ankle / subtalar / mtp axes are taken from gait2354
(those coordinates have the same polarity in both models). The walker knee
flexes *positive* in Rajagopal and *negative* in gait2354, so the knee axes
are reversed here.
"""

import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SOURCE = ROOT / "src" / "argus_server" / "urdf" / "human.urdf"
DEST = ROOT / "src" / "argus_server" / "urdf" / "human_rajagopal_lower.urdf"
GAIT = ROOT / "models" / "gait2354" / "model.osim"
RAJA = HERE / "model.osim"

RENAME = {
    "r_x": "pelvis_tilt", "r_y": "pelvis_list", "r_z": "pelvis_rotation",
    "jRightHip_rotx": "hip_flexion_r", "jRightHip_roty": "hip_adduction_r", "jRightHip_rotz": "hip_rotation_r",
    "jLeftHip_rotx": "hip_flexion_l", "jLeftHip_roty": "hip_adduction_l", "jLeftHip_rotz": "hip_rotation_l",
    "jRightKnee_roty": "knee_angle_r", "jLeftKnee_roty": "knee_angle_l",
    "jRightAnkle_rotx": "ankle_angle_r", "jRightAnkle_roty": "subtalar_angle_r", "jRightBallFoot_roty": "mtp_angle_r",
    "jLeftAnkle_rotx": "ankle_angle_l", "jLeftAnkle_roty": "subtalar_angle_l", "jLeftBallFoot_roty": "mtp_angle_l",
    "jL5S1_rotx": "lumbar_extension", "jL5S1_roty": "lumbar_bending", "jT9T8_rotz": "lumbar_rotation",
}

FLIP_AXIS = {"knee_angle_r", "knee_angle_l"}


def axes_from(path):
    root = ET.parse(path).getroot()
    axes = {}
    for joint in root.iter("CustomJoint"):
        st = joint.find("SpatialTransform")
        if st is None:
            continue
        for ta in st.findall("TransformAxis"):
            coord = (ta.findtext("coordinates") or "").strip()
            if not ta.get("name", "").startswith("rotation") or not coord or coord in axes:
                continue
            axis = [float(v) for v in ta.findtext("axis").split()]
            fn = ta.find("LinearFunction")
            coef = fn.findtext("coefficients") if fn is not None else None
            if coef and float(coef.split()[0]) < 0:
                axis = [-a for a in axis]
            axes[coord] = axis
    return axes


def ranges_from(path):
    root = ET.parse(path).getroot()
    return {c.get("name"): tuple(float(v) for v in c.findtext("range").split())
            for c in root.iter("Coordinate") if c.get("name") and c.findtext("range")}


def ros_axis(osim):
    a, b, c = osim
    return f"{a:g} {-c:g} {b:g}"


def main():
    tree = ET.parse(SOURCE)
    robot = tree.getroot()
    robot.set("name", "human_rajagopal_lower")
    axes = axes_from(GAIT)
    ranges = ranges_from(RAJA)
    renamed = set()
    for joint in robot.findall("joint"):
        name = joint.get("name")
        if name in RENAME:
            coord = RENAME[name]
            axis = list(axes[coord])
            if coord in FLIP_AXIS:
                axis = [-a for a in axis]
            lower, upper = ranges[coord]
            joint.set("name", coord)
            joint.set("type", "revolute")
            for tag in ("axis", "limit", "mimic"):
                for el in joint.findall(tag):
                    joint.remove(el)
            ET.SubElement(joint, "axis", {"xyz": ros_axis(axis)})
            ET.SubElement(joint, "limit", {"lower": f"{lower:g}", "upper": f"{upper:g}",
                                           "effort": "100", "velocity": "10"})
            renamed.add(name)
        elif joint.get("type") in ("revolute", "continuous", "prismatic"):
            joint.set("type", "fixed")
            for tag in ("limit", "mimic"):
                for el in joint.findall(tag):
                    joint.remove(el)
    missing = set(RENAME) - renamed
    if missing:
        raise SystemExit(f"joints not found in {SOURCE.name}: {sorted(missing)}")
    ET.indent(tree, space="  ")
    DEST.write_text(
        "<?xml version=\"1.0\"?>\n"
        "<!-- Generated by models/rajagopal_lower/make_urdf.py from human.urdf; edit that script, not this file. -->\n"
        + ET.tostring(robot, encoding="unicode") + "\n")
    print(f"wrote {DEST} ({len(renamed)} Rajagopal joints)")


if __name__ == "__main__":
    main()
